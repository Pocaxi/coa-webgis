window.WG = window.WG || {};
// Failure classes written by the plugin (labels must match core/config.py).
WG.FAILURE_CLASSES = [
  ['< 0,50 m', '#9ccc65'],
  ['0,50–1,50 m', '#f4d03f'],
  ['1,50–3,00 m', '#3498db'],
  ['3,00–5,00 m', '#f39c12'],
  ['>= 5,00 m', '#e74c3c'],
];
// Attribute names: current prefix first, then the one used by older publications.
WG.field = name => ['coalesce', ['get', `_wg_${name}`], ['get', `_coa_${name}`]];
WG.projectUrl = function(path) {
  const projectBase = new URL((WG.config || window.WG_CONFIG || window.COA_CONFIG || {}).projectBase || './', window.location.href);
  return new URL(String(path || '').replace(/^\/+/, ''), projectBase).href;
};
WG.rasterFiles = async function(project, layer) {
  if (project.orthomosaic && project.orthomosaic.enabled !== false && Array.isArray(project.orthomosaic.files)) {
    return project.orthomosaic.files.slice();
  }
  // Compatibility with project.json generated by 0.3.0 and earlier.
  if (layer.format === 'raster_pmtiles') return [layer.output];
  if (layer.format === 'raster_pmtiles_mosaic') {
    const indexUrl = new URL(WG.projectUrl(layer.output));
    const response = await fetch(indexUrl.href, {cache: 'no-store'});
    if (!response.ok) throw new Error(`Índice do ortomosaico não encontrado: ${layer.output}`);
    const mosaic = await response.json();
    return (mosaic.tiles || []).map(tile => new URL(tile.file, indexUrl).href);
  }
  return [];
};
WG.addProjectLayers = async function(map, project) {
  const queryable = [];
  WG.popupConfigs = {};
  const enabled = (project.layers || []).filter(layer => layer.enabled && layer.output);
  const visualPriority = {orthomosaic: 0, boundary: 1, failures: 2, lines: 3, points: 4};
  const ordered = enabled.slice().sort((a, b) =>
    (visualPriority[a.role] ?? 10) - (visualPriority[b.role] ?? 10)
  );
  for (const [index, layer] of ordered.entries()) {
    const id = `wg-${layer.role}-${index}`;
    const mapIds = [];
    const zoom = {minzoom: layer.minzoom ?? 0, maxzoom: layer.maxzoom ?? 22};
    if (layer.format === 'raster_pmtiles' || layer.format === 'raster_pmtiles_mosaic') {
      const files = await WG.rasterFiles(project, layer);
      if (!files.length) throw new Error('Manifesto do ortomosaico não contém arquivos PMTiles.');
      // The orthomosaic stays visible when zooming past its native resolution.
      const rasterZoom = {minzoom: zoom.minzoom, maxzoom: Math.max(zoom.maxzoom, 24)};
      for (const [partIndex, file] of files.entries()) {
        const partId = `orthomosaic-${partIndex}`;
        const resolvedUrl = /^https?:\/\//i.test(file)
          ? file
          : WG.projectUrl(file);
        map.addSource(partId, {
          type: 'raster', url: `pmtiles://${resolvedUrl}`, tileSize: 256
        });
        map.addLayer({...rasterZoom,
          id: partId, type: 'raster', source: partId,
          layout: {visibility: layer.visible ? 'visible' : 'none'},
          paint: {'raster-opacity': 1, 'raster-fade-duration': 0, 'raster-resampling': 'linear'}
        });
        mapIds.push(partId);
      }
    } else if (layer.format === 'vector_pmtiles') {
      map.addSource(id, {type: 'vector', url: `pmtiles://${WG.projectUrl(layer.output)}`});
      const type = /Point$/.test(layer.geometry_type) ? 'circle' : 'line';
      if (/Polygon$/.test(layer.geometry_type)) {
        const fillId = `${id}-fill`;
        map.addLayer({...zoom, id: fillId, type: 'fill', source: id, 'source-layer': layer.source_layer,
          layout: {visibility: layer.visible ? 'visible' : 'none'},
          paint: {'fill-color': (layer.style || {})['fill-color'] || '#a7d46f', 'fill-opacity': (layer.style || {})['fill-opacity'] ?? .08}});
        mapIds.push(fillId);
      }
      map.addLayer({...zoom,id, type, source: id, 'source-layer': layer.source_layer,
        layout: {visibility: layer.visible ? 'visible' : 'none'},
        paint: WG.paintFor(type, layer.role, layer.style || {})});
      mapIds.push(id);

    } else {
      map.addSource(id, {type: 'geojson', data: WG.projectUrl(layer.output), generateId: true});
      const paint = layer.style || {};
      let type = 'line';
      if (layer.role === 'failures') paint['line-width'] = ['interpolate', ['linear'], ['zoom'], 14, 1.5, 18, ['interpolate', ['linear'], ['to-number', ['coalesce', WG.field('length_m'), 0]], .5, 2.5, 5, 5], 22, ['interpolate', ['linear'], ['to-number', ['coalesce', WG.field('length_m'), 0]], .5, 6, 5, 12]];
      if (/Point$/.test(layer.geometry_type)) type = 'circle';
      if (/Polygon$/.test(layer.geometry_type)) {
        const fillId = `${id}-fill`;
        map.addLayer({...zoom,id: fillId, type: 'fill', source: id,
          layout: {visibility: layer.visible ? 'visible' : 'none'},
          paint: {'fill-color': paint['fill-color'] || '#a7d46f', 'fill-opacity': paint['fill-opacity'] ?? .08}});
        mapIds.push(fillId);
      }
      map.addLayer({...zoom,id, type, source: id, layout: {visibility: layer.visible ? 'visible' : 'none'},
        paint: WG.paintFor(type, layer.role, paint)});
      mapIds.push(id);

    }
    layer._mapIds = mapIds;
    if (layer.queryable && !layer.format.startsWith('raster')) {
      for (const mapId of mapIds) { queryable.push(mapId); WG.popupConfigs[mapId] = layer; }
    }
  }
  WG.renderLayerList(map, project.layers || []);
  return queryable;
};
WG.paintFor = function(type, role, paint) {
  if (type === 'circle') return {'circle-color': paint['circle-color'] || '#8e44ad', 'circle-radius': paint['circle-radius'] || 5, 'circle-stroke-color': '#fff', 'circle-stroke-width': 1};
  if (role === 'failures') return {'line-color': ['match', WG.field('class'), ...WG.FAILURE_CLASSES.flat(), '#f4d03f'], 'line-width': paint['line-width'], 'line-opacity': .95};
  return {'line-color': paint['line-color'] || '#fff', 'line-width': paint['line-width'] || 2, 'line-opacity': paint['line-opacity'] ?? .9};
};
WG.layerLabel = layer => layer.role === 'orthomosaic' ? 'Ortomosaico' : (layer.name || layer.role);
WG.renderLayerList = function(map, layers) {
  const host = document.getElementById('layerList'); host.innerHTML = '';
  layers.filter(layer => layer.enabled).forEach(layer => {
    const row = document.createElement('label'); row.className = 'layer-row';
    const input = document.createElement('input'); input.type = 'checkbox'; input.checked = layer.visible;
    input.onchange = () => (layer._mapIds || []).forEach(id => map.setLayoutProperty(id, 'visibility', input.checked ? 'visible' : 'none'));
    const name = document.createElement('span'); name.textContent = WG.layerLabel(layer);
    const swatch = document.createElement('i'); swatch.className = 'swatch';
    swatch.style.background = layer.role === 'orthomosaic' ? 'linear-gradient(90deg,#6b8e4e,#b9a77a)' : ((layer.style || {})['line-color'] || (layer.style || {})['circle-color'] || '#a7d46f');
    row.append(input, name, swatch); host.append(row);
    if (layer.role === 'orthomosaic') {
      // Fading the orthomosaic makes lines and failures easier to compare with the crop.
      const opacity = document.createElement('input');
      opacity.type = 'range'; opacity.min = '0'; opacity.max = '100'; opacity.value = '100';
      opacity.className = 'opacity-range'; opacity.setAttribute('aria-label', 'Opacidade do ortomosaico');
      opacity.oninput = () => (layer._mapIds || []).forEach(id => map.setPaintProperty && map.setPaintProperty(id, 'raster-opacity', Number(opacity.value) / 100));
      const wrap = document.createElement('div'); wrap.className = 'opacity-row';
      const text = document.createElement('span'); text.textContent = 'Opacidade';
      wrap.append(text, opacity); host.append(wrap);
    }
  });
};
WG.renderLegend = function(project) {
  const section = document.getElementById('legendSection'), host = document.getElementById('legend');
  const hasFailures = (project.layers || []).some(layer => layer.enabled && layer.role === 'failures');
  if (!section || !host || !hasFailures) return;
  const counts = (project.statistics || {}).failure_classes || {};
  host.innerHTML = WG.FAILURE_CLASSES.map(([label, color]) => {
    const count = counts[label];
    const value = count == null ? '' : `<b>${Number(count).toLocaleString('pt-BR')}</b>`;
    return `<div class="legend-row"><i style="background:${color}"></i><span>${WG.escape(label)}</span>${value}</div>`;
  }).join('');
  section.hidden = false;
};
